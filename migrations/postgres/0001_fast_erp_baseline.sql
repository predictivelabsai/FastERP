-- FastERP PostgreSQL baseline and SAP Business One migration control plane.
--
-- Apply with a migration runner inside a transaction, or directly with:
--   psql "$DB_URL" -v ON_ERROR_STOP=1 -1 -f migrations/postgres/0001_fast_erp_baseline.sql
--
-- This migration is intentionally schema-qualified. It does not alter objects
-- outside the fast_erp schema and stores no SAP or database credentials.

CREATE SCHEMA IF NOT EXISTS fast_erp;

CREATE TABLE IF NOT EXISTS fast_erp.schema_migrations (
    version        TEXT PRIMARY KEY,
    applied_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------------------
-- Organisation and shared reference data
-- -------------------------------------------------------------------------

CREATE TABLE fast_erp.currencies (
    code           CHAR(3) PRIMARY KEY,
    name           TEXT NOT NULL,
    symbol         TEXT NOT NULL,
    active         BOOLEAN NOT NULL DEFAULT true,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO fast_erp.currencies (code, name, symbol)
VALUES
    ('EUR', 'Euro', '€'),
    ('GBP', 'Pound sterling', '£'),
    ('USD', 'US dollar', '$')
ON CONFLICT (code) DO NOTHING;

CREATE TABLE fast_erp.companies (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               TEXT NOT NULL UNIQUE,
    name               TEXT NOT NULL,
    country_code       CHAR(2) NOT NULL,
    local_currency     CHAR(3) NOT NULL REFERENCES fast_erp.currencies(code),
    timezone           TEXT NOT NULL DEFAULT 'UTC',
    fiscal_year_start  SMALLINT NOT NULL DEFAULT 1
                       CHECK (fiscal_year_start BETWEEN 1 AND 12),
    active             BOOLEAN NOT NULL DEFAULT true,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE fast_erp.exchange_rates (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id         BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    rate_date          DATE NOT NULL,
    from_currency      CHAR(3) NOT NULL REFERENCES fast_erp.currencies(code),
    to_currency        CHAR(3) NOT NULL REFERENCES fast_erp.currencies(code),
    rate               NUMERIC(20, 10) NOT NULL CHECK (rate > 0),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (company_id, rate_date, from_currency, to_currency),
    CHECK (from_currency <> to_currency)
);

