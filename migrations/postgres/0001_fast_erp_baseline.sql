CREATE TABLE fast_erp.migration_sources (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id             BIGINT REFERENCES fast_erp.companies(id),
    name                   TEXT NOT NULL UNIQUE,
    connector_type         TEXT NOT NULL
                           CHECK (connector_type IN (
                               'sap_business_one_odata_v4',
                               'sap_s4_odata',
                               'sap_ecc',
                               'csv_bundle',
                               'mock_sap'
                           )),
    base_url               TEXT,
    source_company_db      TEXT,
    credential_env_prefix TEXT,
    configuration          JSONB NOT NULL DEFAULT '{}'::jsonb,
    active                 BOOLEAN NOT NULL DEFAULT true,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON COLUMN fast_erp.migration_sources.configuration IS
    'Non-secret connector options only. Credentials are resolved from environment variables.';

CREATE TABLE fast_erp.migration_mapping_sets (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           TEXT NOT NULL,
    version        INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
    source_type    TEXT NOT NULL,
    status         TEXT NOT NULL DEFAULT 'Draft'
                   CHECK (status IN ('Draft', 'Approved', 'Retired')),
    description    TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    approved_at    TIMESTAMPTZ,
    UNIQUE (name, version)
);

CREATE TABLE fast_erp.migration_mapping_rules (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapping_set_id     BIGINT NOT NULL REFERENCES fast_erp.migration_mapping_sets(id)
                       ON DELETE CASCADE,
    source_object      TEXT NOT NULL,
    source_field       TEXT NOT NULL,
    target_table       TEXT NOT NULL,
    target_field       TEXT NOT NULL,
    transform_type     TEXT NOT NULL DEFAULT 'copy'
                       CHECK (transform_type IN (
                           'copy', 'constant', 'lookup', 'expression', 'ignore'
                       )),
    transform_config   JSONB NOT NULL DEFAULT '{}'::jsonb,
    required           BOOLEAN NOT NULL DEFAULT false,
    ordinal            INTEGER NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (mapping_set_id, source_object, source_field, target_table, target_field)
);

CREATE TABLE fast_erp.migration_runs (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id          BIGINT NOT NULL REFERENCES fast_erp.migration_sources(id),
    mapping_set_id     BIGINT REFERENCES fast_erp.migration_mapping_sets(id),
    mode               TEXT NOT NULL DEFAULT 'cutover'
                       CHECK (mode IN ('discovery', 'dry_run', 'cutover')),
    status             TEXT NOT NULL DEFAULT 'Created'
                       CHECK (status IN (
                           'Created', 'Extracting', 'Staged', 'Validating', 'Validated',
                           'Approved', 'Applying', 'Reconciling', 'Completed', 'Failed',
                           'Cancelled'
                       )),
    history_from       DATE NOT NULL,
    history_to         DATE NOT NULL,
    scope              JSONB NOT NULL DEFAULT '{}'::jsonb,
    requested_by       TEXT,
    approved_by        TEXT,
    approved_at        TIMESTAMPTZ,
    started_at         TIMESTAMPTZ,
    completed_at       TIMESTAMPTZ,
    source_count       BIGINT NOT NULL DEFAULT 0,
    staged_count       BIGINT NOT NULL DEFAULT 0,
    applied_count      BIGINT NOT NULL DEFAULT 0,
    warning_count      BIGINT NOT NULL DEFAULT 0,
    error_count        BIGINT NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (history_to >= history_from),
    CHECK ((status <> 'Approved' AND approved_at IS NULL) OR approved_by IS NOT NULL)
);

CREATE TABLE fast_erp.migration_batches (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id             BIGINT NOT NULL REFERENCES fast_erp.migration_runs(id)
                       ON DELETE CASCADE,
    source_object      TEXT NOT NULL,
    sequence_number    INTEGER NOT NULL CHECK (sequence_number >= 0),
    status             TEXT NOT NULL DEFAULT 'Pending'
                       CHECK (status IN ('Pending', 'Extracted', 'Validated', 'Applied', 'Failed')),
    request_cursor     TEXT,
    response_cursor    TEXT,
    source_count       INTEGER NOT NULL DEFAULT 0,
    staged_count       INTEGER NOT NULL DEFAULT 0,
    applied_count      INTEGER NOT NULL DEFAULT 0,
    payload_hash       TEXT,
    started_at         TIMESTAMPTZ,
    completed_at       TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (run_id, source_object, sequence_number)
);

CREATE TABLE fast_erp.migration_staging_records (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id             BIGINT NOT NULL REFERENCES fast_erp.migration_runs(id)
                       ON DELETE CASCADE,
    batch_id           BIGINT REFERENCES fast_erp.migration_batches(id)
                       ON DELETE CASCADE,
    source_object      TEXT NOT NULL,
    source_key         TEXT NOT NULL,
    source_document_no TEXT,
    source_updated_at  TIMESTAMPTZ,
    raw_payload        JSONB NOT NULL,
    normalized_payload JSONB,
    payload_hash       TEXT NOT NULL,
    status             TEXT NOT NULL DEFAULT 'Extracted'
                       CHECK (status IN (
                           'Extracted', 'Mapped', 'Valid', 'Warning', 'Invalid',
                           'Applied', 'Skipped', 'Failed'
                       )),
    target_table       TEXT,
    target_id          BIGINT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (run_id, source_object, source_key)
);

CREATE TABLE fast_erp.migration_validation_issues (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id             BIGINT NOT NULL REFERENCES fast_erp.migration_runs(id)
                       ON DELETE CASCADE,
    staging_record_id  BIGINT REFERENCES fast_erp.migration_staging_records(id)
                       ON DELETE CASCADE,
    severity           TEXT NOT NULL CHECK (severity IN ('Info', 'Warning', 'Error')),
    rule_code          TEXT NOT NULL,
    field_name         TEXT,
    message            TEXT NOT NULL,
    details            JSONB NOT NULL DEFAULT '{}'::jsonb,
    resolved           BOOLEAN NOT NULL DEFAULT false,
    resolution_note    TEXT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at        TIMESTAMPTZ
);

CREATE TABLE fast_erp.migration_crosswalks (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id          BIGINT NOT NULL REFERENCES fast_erp.migration_sources(id),
    source_object      TEXT NOT NULL,
    source_key         TEXT NOT NULL,
    source_document_no TEXT,
    target_table       TEXT NOT NULL,
    target_id          BIGINT NOT NULL,
    payload_hash       TEXT NOT NULL,
    first_run_id       BIGINT NOT NULL REFERENCES fast_erp.migration_runs(id),
    last_run_id        BIGINT NOT NULL REFERENCES fast_erp.migration_runs(id),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source_id, source_object, source_key),
    UNIQUE (source_id, target_table, target_id)
);

CREATE TABLE fast_erp.external_references (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id          BIGINT NOT NULL REFERENCES fast_erp.migration_sources(id),
    entity_type        TEXT NOT NULL,
    entity_id          BIGINT NOT NULL,
    source_object      TEXT NOT NULL,
    source_key         TEXT NOT NULL,
    source_document_no TEXT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source_id, source_object, source_key),
    UNIQUE (source_id, entity_type, entity_id)
);

CREATE TABLE fast_erp.migration_checkpoints (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         BIGINT NOT NULL REFERENCES fast_erp.migration_runs(id)
                   ON DELETE CASCADE,
    source_object  TEXT NOT NULL,
    cursor_value   TEXT,
    last_source_key TEXT,
    completed      BOOLEAN NOT NULL DEFAULT false,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (run_id, source_object)
);

CREATE TABLE fast_erp.migration_reconciliations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         BIGINT NOT NULL REFERENCES fast_erp.migration_runs(id)
                   ON DELETE CASCADE,
    check_code     TEXT NOT NULL,
    object_type    TEXT,
    dimension      JSONB NOT NULL DEFAULT '{}'::jsonb,
    source_value   NUMERIC(30, 8),
    target_value   NUMERIC(30, 8),
    difference     NUMERIC(30, 8),
    passed         BOOLEAN NOT NULL,
    details        JSONB NOT NULL DEFAULT '{}'::jsonb,
    checked_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (run_id, check_code, object_type, dimension)
);

CREATE TABLE fast_erp.migration_audit_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         BIGINT REFERENCES fast_erp.migration_runs(id) ON DELETE CASCADE,
    actor          TEXT,
    event_type     TEXT NOT NULL,
    message        TEXT NOT NULL,
    details        JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

