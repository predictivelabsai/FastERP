-- Physical stock identity, reservations, shelf life, and manual temperature control.

CREATE TABLE fast_erp.temperature_zones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    warehouse_id BIGINT NOT NULL REFERENCES fast_erp.warehouses(id),
    code TEXT NOT NULL,
    name TEXT NOT NULL,
    minimum_c NUMERIC(8, 3) NOT NULL,
    maximum_c NUMERIC(8, 3) NOT NULL,
    reading_interval_hours INTEGER NOT NULL DEFAULT 24 CHECK (reading_interval_hours > 0),
    active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (company_id, warehouse_id, code),
    CHECK (minimum_c < maximum_c)
);

CREATE TABLE fast_erp.warehouse_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    warehouse_id BIGINT NOT NULL REFERENCES fast_erp.warehouses(id),
    parent_id BIGINT REFERENCES fast_erp.warehouse_locations(id),
    temperature_zone_id BIGINT REFERENCES fast_erp.temperature_zones(id),
    code TEXT NOT NULL,
    name TEXT NOT NULL,
    location_type TEXT NOT NULL DEFAULT 'Bin'
        CHECK (location_type IN ('Zone', 'Aisle', 'Shelf', 'Bin', 'Receiving', 'QC', 'Dispatch')),
    pickable BOOLEAN NOT NULL DEFAULT true,
    active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (company_id, warehouse_id, code),
    CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE TABLE fast_erp.stock_slices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    item_id BIGINT NOT NULL REFERENCES fast_erp.items(id),
    warehouse_id BIGINT NOT NULL REFERENCES fast_erp.warehouses(id),
    location_id BIGINT NOT NULL REFERENCES fast_erp.warehouse_locations(id),
    batch_id BIGINT REFERENCES fast_erp.batches(id),
    serial_number_id BIGINT REFERENCES fast_erp.serial_numbers(id),
    disposition TEXT NOT NULL DEFAULT 'Available'
        CHECK (disposition IN ('Available', 'QC', 'Hold', 'Rejected', 'Damaged')),
    quantity NUMERIC(20, 6) NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    reserved_qty NUMERIC(20, 6) NOT NULL DEFAULT 0 CHECK (reserved_qty >= 0 AND reserved_qty <= quantity),
    first_received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE NULLS NOT DISTINCT (company_id, item_id, warehouse_id, location_id,
                               batch_id, serial_number_id, disposition),
    CHECK (serial_number_id IS NULL OR quantity <= 1)
);
CREATE INDEX idx_wms_stock_fefo ON fast_erp.stock_slices
    (company_id, item_id, warehouse_id, disposition, batch_id)
    WHERE quantity > 0;
CREATE INDEX idx_wms_stock_location ON fast_erp.stock_slices(location_id)
    WHERE quantity > 0;

CREATE TABLE fast_erp.inventory_allocation_splits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ledger_entry_id BIGINT NOT NULL REFERENCES fast_erp.inventory_ledger_entries(id),
    company_id BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    item_id BIGINT NOT NULL REFERENCES fast_erp.items(id),
    warehouse_id BIGINT NOT NULL REFERENCES fast_erp.warehouses(id),
    location_id BIGINT NOT NULL REFERENCES fast_erp.warehouse_locations(id),
    batch_id BIGINT REFERENCES fast_erp.batches(id),
    serial_number_id BIGINT REFERENCES fast_erp.serial_numbers(id),
    disposition TEXT NOT NULL
        CHECK (disposition IN ('Available', 'QC', 'Hold', 'Rejected', 'Damaged')),
    quantity_change NUMERIC(20, 6) NOT NULL CHECK (quantity_change <> 0),
    source_split_id BIGINT REFERENCES fast_erp.inventory_allocation_splits(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (serial_number_id IS NULL OR abs(quantity_change) = 1)
);
CREATE TRIGGER inventory_allocation_splits_immutable
BEFORE UPDATE OR DELETE ON fast_erp.inventory_allocation_splits
FOR EACH ROW EXECUTE FUNCTION fast_erp.reject_immutable_ledger_mutation();
CREATE INDEX idx_wms_splits_ledger ON fast_erp.inventory_allocation_splits(ledger_entry_id);
CREATE INDEX idx_wms_splits_lot ON fast_erp.inventory_allocation_splits(company_id, batch_id, created_at);

CREATE TABLE fast_erp.warehouse_transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    item_id BIGINT NOT NULL REFERENCES fast_erp.items(id),
    warehouse_id BIGINT NOT NULL REFERENCES fast_erp.warehouses(id),
    from_location_id BIGINT NOT NULL REFERENCES fast_erp.warehouse_locations(id),
    to_location_id BIGINT NOT NULL REFERENCES fast_erp.warehouse_locations(id),
    batch_id BIGINT REFERENCES fast_erp.batches(id),
    serial_number_id BIGINT REFERENCES fast_erp.serial_numbers(id),
    from_disposition TEXT NOT NULL,
    to_disposition TEXT NOT NULL,
    quantity NUMERIC(20, 6) NOT NULL CHECK (quantity > 0),
    actor TEXT NOT NULL,
    reason TEXT NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (from_location_id <> to_location_id OR from_disposition <> to_disposition)
);
CREATE TRIGGER warehouse_transfers_immutable
BEFORE UPDATE OR DELETE ON fast_erp.warehouse_transfers
FOR EACH ROW EXECUTE FUNCTION fast_erp.reject_immutable_ledger_mutation();
CREATE INDEX idx_wms_transfers_lot ON fast_erp.warehouse_transfers(company_id,batch_id,occurred_at);

CREATE TABLE fast_erp.stock_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    sales_order_item_id BIGINT NOT NULL REFERENCES fast_erp.sales_order_items(id),
    stock_slice_id BIGINT NOT NULL REFERENCES fast_erp.stock_slices(id),
    quantity NUMERIC(20, 6) NOT NULL CHECK (quantity > 0),
    consumed_qty NUMERIC(20, 6) NOT NULL DEFAULT 0
        CHECK (consumed_qty >= 0 AND consumed_qty <= quantity),
    status TEXT NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Consumed', 'Released')),
    reserved_by TEXT NOT NULL,
    reserved_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ,
    released_at TIMESTAMPTZ,
    release_reason TEXT
);
CREATE INDEX idx_wms_reservations_slice ON fast_erp.stock_reservations(stock_slice_id, status);
CREATE UNIQUE INDEX idx_wms_active_order_slice
ON fast_erp.stock_reservations(sales_order_item_id, stock_slice_id)
WHERE status = 'Active';

CREATE TABLE fast_erp.lot_holds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    batch_id BIGINT NOT NULL REFERENCES fast_erp.batches(id),
    reason TEXT NOT NULL,
    created_by TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    released_by TEXT,
    released_at TIMESTAMPTZ,
    release_reason TEXT,
    CHECK ((released_at IS NULL) = (released_by IS NULL))
);
CREATE INDEX idx_wms_active_lot_holds ON fast_erp.lot_holds(company_id, batch_id)
WHERE released_at IS NULL;

CREATE TABLE fast_erp.temperature_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    zone_id BIGINT NOT NULL REFERENCES fast_erp.temperature_zones(id),
    measured_at TIMESTAMPTZ NOT NULL,
    temperature_c NUMERIC(8, 3) NOT NULL,
    recorded_by TEXT NOT NULL,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_wms_temperature_readings ON fast_erp.temperature_readings(zone_id, measured_at DESC);

CREATE TABLE fast_erp.temperature_excursions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    zone_id BIGINT NOT NULL REFERENCES fast_erp.temperature_zones(id),
    reading_id BIGINT NOT NULL UNIQUE REFERENCES fast_erp.temperature_readings(id),
    status TEXT NOT NULL DEFAULT 'Open' CHECK (status IN ('Open', 'Released')),
    opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_by TEXT,
    reviewed_at TIMESTAMPTZ,
    review_reason TEXT,
    CHECK ((status = 'Open') = (reviewed_at IS NULL))
);
CREATE INDEX idx_wms_open_excursions ON fast_erp.temperature_excursions(zone_id)
WHERE status = 'Open';

