                                         location_type, pickable)
SELECT warehouse.company_id, warehouse.id, 'DEFAULT', 'Default location', 'Bin', true
FROM fast_erp.warehouses warehouse
ON CONFLICT (company_id, warehouse_id, code) DO NOTHING;

INSERT INTO fast_erp.stock_slices(company_id, item_id, warehouse_id, location_id,
                                  disposition, quantity)
SELECT balance.company_id, balance.item_id, balance.warehouse_id, location.id,
       CASE WHEN item.tracks_batches OR item.tracks_serials THEN 'Hold' ELSE 'Available' END,
       balance.quantity
FROM fast_erp.inventory_balances balance
JOIN fast_erp.items item ON item.id = balance.item_id
JOIN fast_erp.warehouse_locations location
  ON location.warehouse_id = balance.warehouse_id AND location.code = 'DEFAULT'
WHERE balance.quantity > 0
ON CONFLICT DO NOTHING;

