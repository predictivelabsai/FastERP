CREATE VIEW fast_erp.wms_stock_report AS
SELECT slice.company_id, slice.id AS stock_slice_id,
       slice.location_id, slice.batch_id, slice.serial_number_id,
       item.code AS item_code, item.name AS item_name,
       warehouse.code AS warehouse_code, location.code AS location_code,
       batch.batch_code AS lot_code, batch.expires_on AS expiry_date,
       serial.serial_code, slice.disposition, slice.quantity AS on_hand,
       slice.reserved_qty AS reserved,
       CASE WHEN slice.disposition='Available' AND location.pickable
                 AND (NOT item.tracks_expiry OR batch.expires_on IS NOT NULL)
                 AND (batch.expires_on IS NULL OR batch.expires_on >= current_date)
                 AND NOT EXISTS (SELECT 1 FROM fast_erp.lot_holds hold
                                 WHERE hold.batch_id=slice.batch_id AND hold.released_at IS NULL)
                 AND NOT EXISTS (SELECT 1 FROM fast_erp.temperature_excursions excursion
                                 WHERE excursion.zone_id=location.temperature_zone_id
                                   AND excursion.status='Open')
            THEN slice.quantity-slice.reserved_qty ELSE 0 END AS available,
       CASE WHEN slice.disposition<>'Available' OR
                 (batch.expires_on IS NOT NULL AND batch.expires_on<current_date) OR
                 EXISTS (SELECT 1 FROM fast_erp.lot_holds hold
                         WHERE hold.batch_id=slice.batch_id AND hold.released_at IS NULL) OR
                 EXISTS (SELECT 1 FROM fast_erp.temperature_excursions excursion
                         WHERE excursion.zone_id=location.temperature_zone_id
                           AND excursion.status='Open')
            THEN slice.quantity ELSE 0 END AS held
FROM fast_erp.stock_slices slice
JOIN fast_erp.items item ON item.id=slice.item_id
JOIN fast_erp.warehouses warehouse ON warehouse.id=slice.warehouse_id
JOIN fast_erp.warehouse_locations location ON location.id=slice.location_id
LEFT JOIN fast_erp.batches batch ON batch.id=slice.batch_id
LEFT JOIN fast_erp.serial_numbers serial ON serial.id=slice.serial_number_id
WHERE slice.company_id=current_setting('fasterp.company_id',true)::bigint;

CREATE VIEW fast_erp.wms_movement_report AS
SELECT split.company_id, split.id AS movement_id, event.event_date,
       event.event_type, event.voucher_code,
       item.code AS item_code, item.name AS item_name,
       warehouse.code AS warehouse_code, location.code AS location_code,
       batch.batch_code AS lot_code, serial.serial_code,
       split.disposition, split.quantity_change
FROM fast_erp.inventory_allocation_splits split
JOIN fast_erp.inventory_ledger_entries ledger ON ledger.id=split.ledger_entry_id
JOIN fast_erp.inventory_events event ON event.id=ledger.event_id
JOIN fast_erp.items item ON item.id=split.item_id
JOIN fast_erp.warehouses warehouse ON warehouse.id=split.warehouse_id
JOIN fast_erp.warehouse_locations location ON location.id=split.location_id
LEFT JOIN fast_erp.batches batch ON batch.id=split.batch_id
LEFT JOIN fast_erp.serial_numbers serial ON serial.id=split.serial_number_id
WHERE split.company_id=current_setting('fasterp.company_id',true)::bigint
UNION ALL
SELECT transfer.company_id, -(transfer.id*2) AS movement_id,
       transfer.occurred_at::date AS event_date, 'Transfer' AS event_type,
       'WT-' || transfer.id::text AS voucher_code,
       item.code AS item_code,item.name AS item_name,
       warehouse.code AS warehouse_code,location.code AS location_code,
       batch.batch_code AS lot_code,serial.serial_code,
       transfer.from_disposition AS disposition,-transfer.quantity AS quantity_change
FROM fast_erp.warehouse_transfers transfer
JOIN fast_erp.items item ON item.id=transfer.item_id
JOIN fast_erp.warehouses warehouse ON warehouse.id=transfer.warehouse_id
JOIN fast_erp.warehouse_locations location ON location.id=transfer.from_location_id
LEFT JOIN fast_erp.batches batch ON batch.id=transfer.batch_id
LEFT JOIN fast_erp.serial_numbers serial ON serial.id=transfer.serial_number_id
WHERE transfer.company_id=current_setting('fasterp.company_id',true)::bigint
UNION ALL
SELECT transfer.company_id, -(transfer.id*2+1) AS movement_id,
       transfer.occurred_at::date AS event_date, 'Transfer' AS event_type,
       'WT-' || transfer.id::text AS voucher_code,
       item.code AS item_code,item.name AS item_name,
       warehouse.code AS warehouse_code,location.code AS location_code,
       batch.batch_code AS lot_code,serial.serial_code,
       transfer.to_disposition AS disposition,transfer.quantity AS quantity_change
FROM fast_erp.warehouse_transfers transfer
JOIN fast_erp.items item ON item.id=transfer.item_id
JOIN fast_erp.warehouses warehouse ON warehouse.id=transfer.warehouse_id
JOIN fast_erp.warehouse_locations location ON location.id=transfer.to_location_id
LEFT JOIN fast_erp.batches batch ON batch.id=transfer.batch_id
LEFT JOIN fast_erp.serial_numbers serial ON serial.id=transfer.serial_number_id
WHERE transfer.company_id=current_setting('fasterp.company_id',true)::bigint;

CREATE VIEW fast_erp.wms_lot_report AS
SELECT batch.company_id, batch.id AS batch_id, item.code AS item_code,
       item.name AS item_name, batch.batch_code AS lot_code,
       batch.manufactured_on, batch.expires_on AS expiry_date,
       COALESCE(sum(slice.quantity),0) AS on_hand,
       COALESCE(sum(slice.reserved_qty),0) AS reserved,
       EXISTS (SELECT 1 FROM fast_erp.lot_holds hold WHERE hold.batch_id=batch.id
               AND hold.released_at IS NULL) AS on_hold
FROM fast_erp.batches batch
JOIN fast_erp.items item ON item.id=batch.item_id
LEFT JOIN fast_erp.stock_slices slice ON slice.batch_id=batch.id
WHERE batch.company_id=current_setting('fasterp.company_id',true)::bigint
GROUP BY batch.company_id,batch.id,item.code,item.name,batch.batch_code,
         batch.manufactured_on,batch.expires_on;

CREATE VIEW fast_erp.wms_temperature_report AS
SELECT reading.company_id, reading.id AS reading_id, zone.code AS zone_code,
       warehouse.code AS warehouse_code, reading.measured_at,
       reading.temperature_c, zone.minimum_c, zone.maximum_c,
       reading.recorded_by,
       CASE WHEN excursion.status='Open' THEN true ELSE false END AS open_excursion
FROM fast_erp.temperature_readings reading
JOIN fast_erp.temperature_zones zone ON zone.id=reading.zone_id
JOIN fast_erp.warehouses warehouse ON warehouse.id=zone.warehouse_id
LEFT JOIN fast_erp.temperature_excursions excursion ON excursion.reading_id=reading.id
WHERE reading.company_id=current_setting('fasterp.company_id',true)::bigint;

