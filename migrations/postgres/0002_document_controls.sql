-- Deterministically classify rows created by the baseline/demo model. The old
-- status columns remain operational/derived status, while document_state owns
-- the posting lifecycle from this migration onward.
UPDATE fast_erp.sales_orders
   SET document_state = CASE status
       WHEN 'Draft' THEN 'Draft'
       WHEN 'Cancelled' THEN 'Cancelled'
       WHEN 'Closed' THEN 'Closed'
       ELSE 'Posted' END,
       posted_at = CASE WHEN status NOT IN ('Draft', 'Cancelled') THEN updated_at END,
       cancelled_at = CASE WHEN status = 'Cancelled' THEN updated_at END;

UPDATE fast_erp.invoices
   SET document_state = CASE status
       WHEN 'Cancelled' THEN 'Cancelled'
       ELSE 'Posted' END,
       posted_at = CASE WHEN status <> 'Cancelled' THEN updated_at END,
       cancelled_at = CASE WHEN status = 'Cancelled' THEN updated_at END;

UPDATE fast_erp.purchase_orders
   SET document_state = CASE status
       WHEN 'Draft' THEN 'Draft'
       WHEN 'Cancelled' THEN 'Cancelled'
       ELSE 'Posted' END,
       posted_at = CASE WHEN status NOT IN ('Draft', 'Cancelled') THEN updated_at END,
       cancelled_at = CASE WHEN status = 'Cancelled' THEN updated_at END;

UPDATE fast_erp.payments
   SET document_state = status,
       posted_at = CASE WHEN status = 'Posted' THEN updated_at END,
       cancelled_at = CASE WHEN status = 'Cancelled' THEN updated_at END;

UPDATE fast_erp.expenses
   SET document_state = status,
       posted_at = CASE WHEN status = 'Posted' THEN updated_at END,
       cancelled_at = CASE WHEN status = 'Cancelled' THEN updated_at END;

UPDATE fast_erp.journal_entries
   SET document_state = status,
       posted_at = CASE WHEN status = 'Posted' THEN updated_at END,
       cancelled_at = CASE WHEN status = 'Cancelled' THEN updated_at END;

