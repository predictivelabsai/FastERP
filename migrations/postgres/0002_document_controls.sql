CREATE TABLE fast_erp.document_sequences (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    document_type   TEXT NOT NULL,
    prefix          TEXT NOT NULL,
    next_number     BIGINT NOT NULL DEFAULT 1 CHECK (next_number > 0),
    padding         SMALLINT NOT NULL DEFAULT 6 CHECK (padding BETWEEN 1 AND 18),
    active          BOOLEAN NOT NULL DEFAULT true,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (company_id, document_type)
);

CREATE TABLE fast_erp.fiscal_periods (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    code            TEXT NOT NULL,
    starts_on       DATE NOT NULL,
    ends_on         DATE NOT NULL,
    status          TEXT NOT NULL DEFAULT 'Open'
                    CHECK (status IN ('Open', 'Soft Closed', 'Locked')),
    locked_at       TIMESTAMPTZ,
    locked_by       TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (company_id, code),
    CHECK (ends_on >= starts_on),
    CHECK ((status = 'Locked') = (locked_at IS NOT NULL))
);

CREATE TABLE fast_erp.roles (
