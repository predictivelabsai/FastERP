CREATE TABLE fast_erp.purchase_invoices (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    code            TEXT NOT NULL,
    supplier_id     BIGINT REFERENCES fast_erp.suppliers(id),
    invoice_type    TEXT NOT NULL DEFAULT 'Invoice'
                    CHECK (invoice_type IN ('Invoice', 'Debit Note')),
    supplier_reference TEXT,
    invoice_date    DATE NOT NULL,
    due_date        DATE,
    currency        CHAR(3) NOT NULL REFERENCES fast_erp.currencies(code),
    exchange_rate   NUMERIC(20, 10) NOT NULL DEFAULT 1 CHECK (exchange_rate > 0),
    net_total       NUMERIC(20, 4) NOT NULL DEFAULT 0 CHECK (net_total >= 0),
    tax_total       NUMERIC(20, 4) NOT NULL DEFAULT 0 CHECK (tax_total >= 0),
    total           NUMERIC(20, 4) NOT NULL DEFAULT 0 CHECK (total >= 0),
    base_net_total  NUMERIC(20, 4) NOT NULL DEFAULT 0 CHECK (base_net_total >= 0),
    base_tax_total  NUMERIC(20, 4) NOT NULL DEFAULT 0 CHECK (base_tax_total >= 0),
    base_total      NUMERIC(20, 4) NOT NULL DEFAULT 0 CHECK (base_total >= 0),
    outstanding_amount NUMERIC(20, 4) NOT NULL DEFAULT 0 CHECK (outstanding_amount >= 0),
    payment_term_id BIGINT REFERENCES fast_erp.payment_terms(id),
    return_against_id BIGINT REFERENCES fast_erp.purchase_invoices(id),
    document_state  TEXT NOT NULL DEFAULT 'Draft'
                    CHECK (document_state IN ('Draft', 'Pending Approval', 'Approved', 'Posted', 'Held', 'Closed', 'Cancelled')),
    status          TEXT NOT NULL DEFAULT 'Unpaid'
                    CHECK (status IN ('Unpaid', 'Partly Paid', 'Paid', 'Overdue', 'Held', 'Cancelled')),
    revision        INTEGER NOT NULL DEFAULT 1 CHECK (revision > 0),
    row_version     BIGINT NOT NULL DEFAULT 1,
    posted_at       TIMESTAMPTZ,
    posted_by       TEXT,
    cancelled_at    TIMESTAMPTZ,
    cancelled_by    TEXT,
    reversal_of_id  BIGINT REFERENCES fast_erp.purchase_invoices(id),
    note            TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (company_id, code),
    CHECK (due_date IS NULL OR due_date >= invoice_date),
    CHECK ((invoice_type = 'Debit Note') = (return_against_id IS NOT NULL))
);

