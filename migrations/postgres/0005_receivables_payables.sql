ALTER TABLE fast_erp.payments
    ADD CONSTRAINT payments_type_check CHECK (payment_type IN ('Customer Receipt', 'Supplier Payment', 'Internal Transfer')),
    ADD CONSTRAINT payments_party_check CHECK (
        (payment_type = 'Customer Receipt' AND customer_id IS NOT NULL AND supplier_id IS NULL)
        OR (payment_type = 'Supplier Payment' AND supplier_id IS NOT NULL AND customer_id IS NULL)
        OR (payment_type = 'Internal Transfer' AND customer_id IS NULL AND supplier_id IS NULL)
    );

UPDATE fast_erp.payments payment
   SET base_amount = COALESCE(base_amount, amount * exchange_rate),
       unallocated_amount = GREATEST(
           amount - COALESCE((
               SELECT sum(allocation.amount)
                 FROM fast_erp.payment_allocations allocation
                WHERE allocation.payment_id = payment.id
           ), 0),
           0
       );

CREATE TABLE fast_erp.supplier_payment_allocations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
