    purchase_invoice_id BIGINT NOT NULL REFERENCES fast_erp.purchase_invoices(id),
    amount          NUMERIC(20, 4) NOT NULL CHECK (amount > 0),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (payment_id, purchase_invoice_id)
