CREATE TABLE fast_erp.party_ledger_entries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    partner_id      BIGINT NOT NULL REFERENCES fast_erp.business_partners(id),
    partner_role    TEXT NOT NULL CHECK (partner_role IN ('Customer', 'Supplier')),
    posting_date    DATE NOT NULL,
    due_date        DATE,
    voucher_type    TEXT NOT NULL,
    voucher_id      BIGINT NOT NULL,
    voucher_code    TEXT NOT NULL,
    currency        CHAR(3) NOT NULL REFERENCES fast_erp.currencies(code),
    debit           NUMERIC(20, 4) NOT NULL DEFAULT 0 CHECK (debit >= 0),
    credit          NUMERIC(20, 4) NOT NULL DEFAULT 0 CHECK (credit >= 0),
    base_debit      NUMERIC(20, 4) NOT NULL DEFAULT 0 CHECK (base_debit >= 0),
    base_credit     NUMERIC(20, 4) NOT NULL DEFAULT 0 CHECK (base_credit >= 0),
    is_advance      BOOLEAN NOT NULL DEFAULT false,
    reverses_entry_id BIGINT REFERENCES fast_erp.party_ledger_entries(id),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((debit > 0 AND credit = 0) OR (credit > 0 AND debit = 0)),
    CHECK ((base_debit > 0 AND base_credit = 0) OR (base_credit > 0 AND base_debit = 0)),
    UNIQUE (company_id, voucher_type, voucher_id, partner_role)
);

CREATE TABLE fast_erp.party_ledger_allocations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    source_entry_id BIGINT NOT NULL REFERENCES fast_erp.party_ledger_entries(id),
    target_entry_id BIGINT NOT NULL REFERENCES fast_erp.party_ledger_entries(id),
    allocation_date DATE NOT NULL,
    amount          NUMERIC(20, 4) NOT NULL CHECK (amount > 0),
    base_amount     NUMERIC(20, 4) NOT NULL CHECK (base_amount > 0),
    exchange_gain_loss NUMERIC(20, 4) NOT NULL DEFAULT 0,
    reversed_by_id  BIGINT REFERENCES fast_erp.party_ledger_allocations(id),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (source_entry_id <> target_entry_id)
);

CREATE TABLE fast_erp.payment_schedules (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type     TEXT NOT NULL CHECK (entity_type IN ('Sales Invoice', 'Purchase Invoice')),
    entity_id       BIGINT NOT NULL,
    installment_number INTEGER NOT NULL CHECK (installment_number > 0),
    due_date        DATE NOT NULL,
    amount          NUMERIC(20, 4) NOT NULL CHECK (amount > 0),
    discount_date   DATE,
    discount_amount NUMERIC(20, 4),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (entity_type, entity_id, installment_number)
);

