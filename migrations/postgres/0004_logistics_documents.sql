CREATE TABLE fast_erp.sales_deliveries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    code            TEXT NOT NULL,
    customer_id     BIGINT REFERENCES fast_erp.customers(id),
    document_kind   TEXT NOT NULL DEFAULT 'Delivery'
                    CHECK (document_kind IN ('Delivery', 'Return')),
    delivery_date   DATE NOT NULL,
    document_state  TEXT NOT NULL DEFAULT 'Draft'
                    CHECK (document_state IN ('Draft', 'Pending Approval', 'Approved', 'Posted', 'Held', 'Closed', 'Cancelled')),
    status          TEXT NOT NULL DEFAULT 'Draft'
                    CHECK (status IN ('Draft', 'To Bill', 'Partly Billed', 'Completed', 'Return', 'Cancelled', 'Closed')),
    return_against_id BIGINT REFERENCES fast_erp.sales_deliveries(id),
    revision        INTEGER NOT NULL DEFAULT 1 CHECK (revision > 0),
    row_version     BIGINT NOT NULL DEFAULT 1,
    posted_at       TIMESTAMPTZ,
    posted_by       TEXT,
    cancelled_at    TIMESTAMPTZ,
    cancelled_by    TEXT,
    reversal_of_id  BIGINT REFERENCES fast_erp.sales_deliveries(id),
    note            TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (company_id, code),
    CHECK ((document_kind = 'Return') = (return_against_id IS NOT NULL))
);

CREATE TABLE fast_erp.sales_delivery_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id     BIGINT NOT NULL REFERENCES fast_erp.sales_deliveries(id) ON DELETE CASCADE,
    line_number     INTEGER NOT NULL,
    sales_order_item_id BIGINT REFERENCES fast_erp.sales_order_items(id),
    item_id         BIGINT NOT NULL REFERENCES fast_erp.items(id),
    warehouse_id    BIGINT NOT NULL REFERENCES fast_erp.warehouses(id),
    uom_id          BIGINT REFERENCES fast_erp.uoms(id),
    qty             NUMERIC(20, 6) NOT NULL CHECK (qty > 0),
    stock_qty       NUMERIC(20, 6) NOT NULL CHECK (stock_qty > 0),
    unit_cost       NUMERIC(20, 6),
    billed_qty      NUMERIC(20, 6) NOT NULL DEFAULT 0 CHECK (billed_qty >= 0),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (delivery_id, line_number)
);

