CREATE TABLE fast_erp.purchase_receipt_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id      BIGINT NOT NULL REFERENCES fast_erp.purchase_receipts(id) ON DELETE CASCADE,
    line_number     INTEGER NOT NULL,
    purchase_order_item_id BIGINT REFERENCES fast_erp.purchase_order_items(id),
    item_id         BIGINT NOT NULL REFERENCES fast_erp.items(id),
    accepted_warehouse_id BIGINT REFERENCES fast_erp.warehouses(id),
    rejected_warehouse_id BIGINT REFERENCES fast_erp.warehouses(id),
    uom_id          BIGINT REFERENCES fast_erp.uoms(id),
    accepted_qty    NUMERIC(20, 6) NOT NULL DEFAULT 0 CHECK (accepted_qty >= 0),
    rejected_qty    NUMERIC(20, 6) NOT NULL DEFAULT 0 CHECK (rejected_qty >= 0),
    stock_qty       NUMERIC(20, 6) NOT NULL CHECK (stock_qty > 0),
    unit_cost       NUMERIC(20, 6),
    billed_qty      NUMERIC(20, 6) NOT NULL DEFAULT 0 CHECK (billed_qty >= 0),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (receipt_id, line_number),
    CHECK (accepted_qty + rejected_qty > 0),
    CHECK (accepted_qty = 0 OR accepted_warehouse_id IS NOT NULL),
    CHECK (rejected_qty = 0 OR rejected_warehouse_id IS NOT NULL)
);

