CREATE OR REPLACE FUNCTION fast_erp.assert_posting_batch_balanced()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    debit_total NUMERIC(30, 4);
    credit_total NUMERIC(30, 4);
    line_count BIGINT;
BEGIN
    IF NEW.status = 'Posted' AND OLD.status IS DISTINCT FROM 'Posted' THEN
        SELECT COALESCE(sum(debit), 0), COALESCE(sum(credit), 0), count(*)
          INTO debit_total, credit_total, line_count
          FROM fast_erp.gl_entries
         WHERE posting_batch_id = NEW.id;
        IF line_count < 2 OR debit_total <> credit_total OR debit_total = 0 THEN
            RAISE EXCEPTION 'posting batch % is not balanced: debit %, credit %, lines %',
                NEW.id, debit_total, credit_total, line_count
                USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER posting_batch_balance_check
BEFORE UPDATE OF status ON fast_erp.posting_batches
FOR EACH ROW EXECUTE FUNCTION fast_erp.assert_posting_batch_balanced();

CREATE TRIGGER gl_entries_immutable_update
