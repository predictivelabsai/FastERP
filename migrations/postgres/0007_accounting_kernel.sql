CREATE TABLE fast_erp.posting_batches (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      BIGINT NOT NULL REFERENCES fast_erp.companies(id),
    voucher_type    TEXT NOT NULL,
    voucher_id      BIGINT NOT NULL,
    voucher_code    TEXT NOT NULL,
    posting_date    DATE NOT NULL,
    status          TEXT NOT NULL DEFAULT 'Draft'
                    CHECK (status IN ('Draft', 'Posted', 'Reversed')),
    reverses_batch_id BIGINT REFERENCES fast_erp.posting_batches(id),
    posted_at       TIMESTAMPTZ,
    posted_by       TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (company_id, voucher_type, voucher_id),
    CHECK ((status = 'Posted') = (posted_at IS NOT NULL) OR status = 'Reversed')
);

